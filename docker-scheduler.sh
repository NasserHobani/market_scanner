#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════
#  المجدول — عمليةٌ واحدة، لا واحدة لكل عامل
# ═══════════════════════════════════════════════════════════════
#
# ═══ لماذا حاوية مستقلّة ═══
#
# ‏cron.start() يعمل في ``AppConfig.ready()`` — أي في **كل عامل
# gunicorn**. وثلاثة عمّال يعني ثلاثة محرّكات على قاعدةٍ واحدة،
# فتُمسح السوق ثلاث مرّات وتُفتح الصفقة الورقية ثلاثاً. والكود
# نفسه يحذّر من هذا: «محرّكان معاً على قاعدة واحدة، فتُشغَّل
# المهمّة مرّتين».
#
# فالويب يعمل بـ ``SCHEDULER_ENGINE=off``، وهذه الحاوية — نسخة
# واحدة لا غير — تنادي ``run_jobs`` الذي بُني لهذا بالضبط: يسأل
# القاعدة عن المستحقّ، يشغّله، ويخرج.
#
# ═══ ولماذا حلقة bash لا عمليةٌ مقيمة ═══
#
# العملية المقيمة تحمل حالتها في الذاكرة: تسريبٌ في pandas أو
# مرجعٌ معلّق ينمو أياماً. وهذه تخرج بعد كل دورة فتُحرَّر الذاكرة
# كاملة — وعطبٌ يُسقط دورةً واحدة لا يُسقط الجدولة كلّها.
set -uo pipefail
# ‏لا ‎-e‎ عمداً: فشل دورةٍ واحدة (انقطاع شبكة عن باينانس مثلاً)
# يجب ألّا يُنهي الحاوية. والخطأ يُسجَّل وتُنتظر الدورة التالية.

# بلا ‎-e‎ لا يوقف فشلُ ``cd`` السكربت — فيعمل manage.py من
# مجلّدٍ آخر ويفشل كل استيراد بلا سببٍ ظاهر.
cd /app || { echo "✗ لا يوجد /app" >&2; exit 1; }

INTERVAL="${SCHEDULER_INTERVAL_SECONDS:-60}"

# ‏SIGTERM من ``docker stop`` يجب أن يُنهي الانتظار فوراً لا بعد
# دقيقة. وبلا هذا ينتظر Docker عشر ثوانٍ ثمّ يقتل العملية قسراً —
# في منتصف كتابة صفقة أحياناً.
running=1
trap 'running=0; printf "\n⚙ أُمرت بالتوقّف — أُنهي بعد الدورة الحالية\n"' \
     TERM INT

printf '⚙ المجدول يعمل كل %s ثانية\n' "$INTERVAL"

while [ "$running" -eq 1 ]; do
  started=$(date +%s)

  python web/manage.py run_jobs || \
    printf '⚠ فشلت دورة الجدولة (%s) — أتابع\n' "$(date -Is)"

  [ "$running" -eq 1 ] || break

  # ═══ الانتظار يُقاس من بداية الدورة ═══
  #
  # ``sleep 60`` بعد دورةٍ استغرقت أربعين ثانية يعني فترةً فعلية
  # مئة ثانية — وتزحف مع طول الدورات حتى تصير المهمّة «كل خمس
  # دقائق» كل ثمانٍ، بلا أن يُظهر شيءٌ السبب.
  elapsed=$(( $(date +%s) - started ))
  wait_for=$(( INTERVAL - elapsed ))
  [ "$wait_for" -gt 0 ] && sleep "$wait_for" &
  wait $! 2>/dev/null || true
done

printf '⚙ توقّف المجدول\n'
