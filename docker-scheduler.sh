#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════
#  المجدول — عمليةٌ واحدة، لا واحدة لكل عامل
# ═══════════════════════════════════════════════════════════════
#
# ═══ لماذا حاوية مستقلّة ═══
#
# ‏cron.start() يعمل في ``AppConfig.ready()`` — أي في **كل عامل
# gunicorn**. وثلاثة عمّال يعني ثلاثة محرّكات على قاعدةٍ واحدة،
# فتُمسح السوق ثلاث مرّات وتُفتح الصفقة الورقية ثلاثاً. والكود
# نفسه يحذّر من هذا: «محرّكان معاً على قاعدة واحدة، فتُشغَّل
# المهمّة مرّتين».
#
# فالويب يعمل بـ ``SCHEDULER_ENGINE=off``، وهذه الحاوية — نسخة
# واحدة لا غير — تنادي ``run_jobs`` الذي بُني لهذا بالضبط: يسأل
# القاعدة عن المستحقّ، يشغّله، ويخرج.
#
# ═══ ولماذا حلقة bash لا عمليةٌ مقيمة ═══
#
# العملية المقيمة تحمل حالتها في الذاكرة: تسريبٌ في pandas أو
# مرجعٌ معلّق ينمو أياماً. وهذه تخرج بعد كل دورة فتُحرَّر الذاكرة
# كاملة — وعطبٌ يُسقط دورةً واحدة لا يُسقط الجدولة كلّها.
set -uo pipefail
# ‏لا ‎-e‎ عمداً: فشل دورةٍ واحدة (انقطاع شبكة عن باينانس مثلاً)
# يجب ألّا يُنهي الحاوية. والخطأ يُسجَّل وتُنتظر الدورة التالية.

# بلا ‎-e‎ لا يوقف فشلُ ``cd`` السكربت — فيعمل manage.py من
# مجلّدٍ آخر ويفشل كل استيراد بلا سببٍ ظاهر.
cd /app || { echo "✗ لا يوجد /app" >&2; exit 1; }

INTERVAL="${SCHEDULER_INTERVAL_SECONDS:-60}"
# ═══ ميزانية المسار الثقيل ═══
#
# دورةٌ ثقيلة بلا سقف تعمل ساعاتٍ حين تتراكم المهامّ، فتُجوِّع
# باقي الثقيل. والميزانية تُفحَص **قبل** حجز كل مهمّة — فما لم
# يُحجَز يبقى مستحقّاً ولا يُتخطّى صامتاً.
HEAVY_BUDGET="${SCHEDULER_HEAVY_BUDGET_SECONDS:-1500}"

# ‏SIGTERM من ``docker stop`` يجب أن يُنهي الانتظار فوراً لا بعد
# دقيقة. وبلا هذا ينتظر Docker عشر ثوانٍ ثمّ يقتل العملية قسراً —
# في منتصف كتابة صفقة أحياناً.
running=1
# ═══ والإشارة لا تبلغ الابن وحدها ═══
#
# ``docker stop`` يرسل SIGTERM إلى العملية **الأولى** فقط. وحلقة
# المسار الثقيل تعمل في الخلفية بنسختها الخاصّة من ``running`` —
# فلا تراها تتغيّر أبداً، وتبقى تعمل بعد أمر التوقّف.
#
# فتُمرَّر الإشارة إليها صراحةً.
trap 'running=0
      [ -n "${HEAVY_PID:-}" ] && kill -TERM "$HEAVY_PID" 2>/dev/null
      printf "\n⚙ أُمرت بالتوقّف — أُنهي بعد الدورة الحالية\n"' \
     TERM INT

# ═══ أقفال المزامنة المتروكة ═══
#
# قفل الزوج ملفٌّ يُحذف في ``finally``. وما لا يمرّ بـ‎finally‎
# يبقى: حاويةٌ قُتلت، أو ‎docker stop‎ بلغ مهلته في منتصف جلب.
# فتعود كل مزامنةٍ تالية لذلك الزوج ``locked`` بلا خطأ ولا سجلّ،
# وتشيخ شموعه، وتُعلن البوّابة «بيانات السوق متأخرة جداً».
#
# ولحظة الإقلاع هي الوحيدة التي يُعلَم فيها يقيناً أنّ لا مزامنة
# جارية — فالحذف هنا آمنٌ بالبناء. والأقفال التي تُترك **أثناء**
# التشغيل يستعيدها ``sync_lock`` بالعمر.
python -c "from scanner.market_sync import locks; n=locks.clear_all(); print(f'⚙ حُذف {n} قفلاً متروكاً' if n else '⚙ لا أقفال متروكة')" \
  || printf '⚠ تعذّر تنظيف الأقفال — أتابع\n'

# ═══════════════════════════════════════════════════════════════
#  مساران لا واحد — وهذا هو إصلاح التأخّر
# ═══════════════════════════════════════════════════════════════
#
# ═══ ما كان ═══
#
# ``run_jobs`` يشغّل كل مستحقٍّ بالتسلسل، والحلقة تنتظر الدفعة
# كلّها. فطولُ الدورة = مجموع مُدد كل المهامّ المستحقّة.
#
# والمقيس: مسحُ الكريبتو وحده اثنتا عشرة دقيقة، والمزامنة نحو
# ١٩٠٠ طلب. فدورةٌ فيها مسحٌ ومزامنة وانضغاط وتحليلٌ من الأعلى
# للأسفل تبلغ أربعين دقيقة بسهولة.
#
# و``settlement`` فترتها **ثلاث دقائق**. لا تستطيع أن تعمل أكثر
# من مرّةٍ في الدورة — فصارت كل أربعين دقيقة. متأخّرةً ثلاثة عشر
# ضعفاً، وشاشتُها تقول «نجحت».
#
# ═══ وما صار ═══
#
# حلقتان مستقلّتان في العملية نفسها:
#
#   الخفيف   كل ‎$INTERVAL‎ — حسم · مراقبة · محفظة · تنبيهات
#   الثقيل   متتابعة بلا انتظار — مسح · مزامنة · انضغاط · تدريب
#
# والثقيلة في الخلفية بـ‎&‎، فلا تحجب الخفيفة دقيقةً واحدة.
# وتسلسلُها مع نفسها محفوظ: حلقةٌ واحدة تنتظر أمرها قبل التالي،
# فلا يتراكم مسحان.

heavy_loop() {
  # نسختها الخاصّة: ``running`` في الأب لا تُرى هنا
  h_running=1
  trap 'h_running=0' TERM INT
  while [ "$h_running" -eq 1 ]; do
    h_started=$(date +%s)
    python web/manage.py run_jobs --lane heavy --budget "$HEAVY_BUDGET" || \
      printf '⚠ فشلت دورة ثقيلة (%s) — أتابع\n' "$(date -Is)"
    [ "$h_running" -eq 1 ] || break
    # ═══ ولو انتهت فوراً ═══
    #
    # دورةٌ بلا مستحقّ تنتهي في ثانية. وبلا انتظارٍ أدنى تصير
    # حلقةً محمومة تستهلك معالجاً كاملاً على استعلامٍ فارغ.
    h_elapsed=$(( $(date +%s) - h_started ))
    [ "$h_elapsed" -lt 30 ] && sleep $(( 30 - h_elapsed ))
  done
}

printf '⚙ المجدول يعمل: خفيف كل %sث · ثقيل متتابع بميزانية %sث\n' \
       "$INTERVAL" "$HEAVY_BUDGET"

heavy_loop &
HEAVY_PID=$!

while [ "$running" -eq 1 ]; do
  started=$(date +%s)

  # ═══ نبضة الحياة ═══
  #
  # صورةٌ واحدة لخدمتين، و``HEALTHCHECK`` فيها يسأل الويب على
  # ‎127.0.0.1:8000‎. والمجدول لا يرفع خادماً — فكان «غير سليم»
  # أبداً: ١٩٨ فشلاً في ساعتين، وكلّها كاذبة.
  #
  # والعلاج ليس إطفاء الفحص بل فحصاً يعني شيئاً: الملفّ يُلمَس عند
  # بداية كل دورة، و‎compose‎ يسأل عن عمره. فحلقةٌ متوقّفة أو
  # معلّقة تظهر، والدورة الطويلة المشروعة لا تُتَّهم.
  : > /tmp/scheduler-heartbeat

  python web/manage.py run_jobs --lane light || \
    printf '⚠ فشلت دورة خفيفة (%s) — أتابع\n' "$(date -Is)"

  [ "$running" -eq 1 ] || break

  # ═══ الانتظار يُقاس من بداية الدورة ═══
  #
  # ``sleep 60`` بعد دورةٍ استغرقت أربعين ثانية يعني فترةً فعلية
  # مئة ثانية — وتزحف مع طول الدورات حتى تصير المهمّة «كل خمس
  # دقائق» كل ثمانٍ، بلا أن يُظهر شيءٌ السبب.
  elapsed=$(( $(date +%s) - started ))
  wait_for=$(( INTERVAL - elapsed ))
  [ "$wait_for" -gt 0 ] && sleep "$wait_for" &
  wait $! 2>/dev/null || true
done

# ═══ والثقيلة تُنتظَر ═══
#
# قتلُ العملية والمسح في منتصفه يترك صفقةً نصف مكتوبة وقفلَ زوجٍ
# غير محرَّر. و``running=0`` قد بلغها عبر ``trap``، فهي تُنهي ما
# في يدها ثمّ تخرج.
if [ -n "${HEAVY_PID:-}" ]; then
  printf '⚙ أنتظر الدورة الثقيلة…\n'
  wait "$HEAVY_PID" 2>/dev/null || true
fi

printf '⚙ توقّف المجدول\n'
